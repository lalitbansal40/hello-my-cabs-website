/**
 * Build the redirect files for hellomycab.com → www.hellomycabs.com, from map.json.
 *
 *   node scripts/seo/old-domain/make-redirects.mjs
 *
 * hellomycab.com is this business's own site since 2017 — 124 pages in the index, the same
 * phone number, the same routes — and today it competes with the new site instead of
 * handing it nine years of standing. Control of it has been lost; the day it comes back,
 * these files move every one of its pages to the matching new page with a 301, which is how
 * a search engine carries a page's ranking to its new address.
 *
 * Writes, next to this script:
 *   htaccess.txt        — for the WordPress hosting (Apache), if that account is recovered
 *   cloudflare-bulk.csv — for Cloudflare Bulk Redirects, if only the domain is recovered
 *
 * map.json is the single source. README.md says which file to use and how.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('.', import.meta.url);
const map = JSON.parse(readFileSync(new URL('map.json', here), 'utf8'));
const origin = map.newOrigin.replace(/\/+$/, '');

// Every `from` is a path with a trailing slash, the WordPress form. Match with or without it.
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// ── Apache ──────────────────────────────────────────────────────────────────
const apache = [
  '# hellomycab.com → www.hellomycabs.com — generated by scripts/seo/old-domain/make-redirects.mjs',
  '# Paste at the TOP of .htaccess, above the WordPress block. Every rule is a permanent (301)',
  '# redirect; the last one sends anything not listed (wp-admin, feeds, ?p=, categories, old',
  '# attachments) to the new home page, so nothing on the old domain is left serving content.',
  '<IfModule mod_rewrite.c>',
  'RewriteEngine On',
  '',
];
for (const { from, to } of map.redirects) {
  if (from === '/') {
    apache.push(`RewriteRule ^$ ${origin}${to} [R=301,L]`);
    continue;
  }
  const path = escape(from.replace(/^\/|\/$/g, ''));
  apache.push(`RewriteRule ^${path}/?$ ${origin}${to} [R=301,L]`);
}
apache.push(
  '',
  `# Everything else on the old domain`,
  `RewriteRule ^ ${origin}${map.fallback} [R=301,L]`,
);
apache.push('</IfModule>', '');
writeFileSync(new URL('htaccess.txt', here), apache.join('\n'));

// ── Cloudflare Bulk Redirects ───────────────────────────────────────────────
// Source URLs without a scheme match both http and https. Both the bare and the www host are
// listed, because the old site answered on both.
const csv = ['source_url,target_url,status_code,preserve_query_string,subpath_matching'];
for (const host of [map.oldHost, `www.${map.oldHost}`]) {
  for (const { from, to } of map.redirects) {
    csv.push(`${host}${from},${origin}${to},301,false,false`);
    if (from !== '/') csv.push(`${host}${from.replace(/\/$/, '')},${origin}${to},301,false,false`);
  }
}
writeFileSync(new URL('cloudflare-bulk.csv', here), csv.join('\n') + '\n');

console.log(
  `htaccess.txt: ${map.redirects.length} rules + fallback · cloudflare-bulk.csv: ${csv.length - 1} rows`,
);
