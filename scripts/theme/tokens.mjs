import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = JSON.parse(readFileSync(resolve(root, 'src/design/web-theme.json'), 'utf8'));
const keys = Object.keys(source.light);
if (keys.join() !== Object.keys(source.dark).join()) throw Error('Theme roles differ');
const lines = ['/* Generated by scripts/theme/tokens.mjs. Edit web-theme.json, then regenerate. */', '@theme inline {'];
for (const key of keys.filter(k => !k.startsWith('shadow-'))) lines.push(`  --color-hmc-${key}: var(--hmc-${key});`);
lines.push('}');
const declarations = (mode, important = '') => keys.map(key => {
 const value = source[mode][key];
 if (!key.startsWith('shadow-') && !/^#[a-f0-9]{6}$/i.test(value)) throw Error(`Invalid ${mode}/${key}`);
 return `  ${key === 'shadow-ticket' ? '--hmc-ticket-shadow' : key.startsWith('shadow-') ? '--' + key : '--hmc-' + key}: ${value}${important};`;
});
for (const mode of ['light', 'dark']) {
 lines.push(mode === 'light' ? ':root, [data-theme="light"] {' : '[data-theme="dark"] {', `  color-scheme: ${mode};`, ...declarations(mode), '}');
}
lines.push('@media print { :root, [data-theme] {', '  color-scheme: light !important;', ...declarations('light', ' !important'), '} }', '');
const output = lines.join('\n'), target = resolve(root, 'src/design/web-theme.css');
if (process.argv.includes('--check')) { if (readFileSync(target, 'utf8') !== output) throw Error('Generated theme CSS drift'); }
else writeFileSync(target, output);
console.log('Theme roles:', keys.length, 'per mode');
