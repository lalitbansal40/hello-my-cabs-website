/**
 * node scripts/brand/og-photos.mjs — writes src/lib/og-photos.generated.ts.
 *
 * The share cards (lib/og.tsx) are drawn by Satori, which reads JPEG and PNG but not WebP,
 * and the card is rendered inside a server function where public/ is not reliably on disk
 * (Amplify serves it from the CDN). So each city photo goes into the card as a small JPEG
 * data URL, from the same WebP the pages show (public/img/cities), cropped the same way.
 * Re-run when a photo in content/city-images.ts changes.
 */
import sharp from 'sharp';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'public/img/cities';
const out = 'src/lib/og-photos.generated.ts';
const rows = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.webp')).sort()) {
  const buf = await sharp(join(dir, f)).resize(400, 300, { fit: 'cover' }).jpeg({ quality: 60, mozjpeg: true }).toBuffer();
  rows.push(`  '/img/cities/${f}': 'data:image/jpeg;base64,${buf.toString('base64')}',`);
  console.log(f, Math.round(buf.length / 1024) + 'KB');
}
writeFileSync(
  out,
  `/* Generated by scripts/brand/og-photos.mjs — do not edit. Each city photo (content/city-images.ts),\n` +
    ` * 400×300 JPEG, for the share cards (lib/og.tsx). */\n` +
    `export const OG_PHOTOS: Record<string, string> = {\n${rows.join('\n')}\n};\n`,
);
